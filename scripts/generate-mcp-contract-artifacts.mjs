#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');

function parseArgs(argv) {
  const out = {
    check: false,
    manifest: path.resolve(
      repoRoot,
      'docs/runtime-migration/contracts/runtime-v1/mcp-tooling.manifest.json'
    ),
  };

  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--check') {
      out.check = true;
      continue;
    }
    if (arg === '--manifest' && argv[i + 1]) {
      out.manifest = path.resolve(repoRoot, argv[++i]);
    }
  }
  return out;
}

function fail(message) {
  console.error(`mcp-contract-codegen: ${message}`);
  process.exit(1);
}

function readJson(filePath) {
  if (!fs.existsSync(filePath)) {
    fail(`manifest not found: ${path.relative(repoRoot, filePath)}`);
  }
  try {
    return JSON.parse(fs.readFileSync(filePath, 'utf8'));
  } catch (error) {
    const msg = error instanceof Error ? error.message : String(error);
    fail(`invalid json at ${path.relative(repoRoot, filePath)}: ${msg}`);
  }
}

function assertStringArray(value, keyPath) {
  if (!Array.isArray(value) || value.length === 0) {
    fail(`${keyPath} must be a non-empty string array`);
  }
  for (const item of value) {
    if (typeof item !== 'string' || item.trim().length === 0) {
      fail(`${keyPath} contains invalid string value`);
    }
  }
}

function assertToolDefinitions(value, keyPath) {
  if (!Array.isArray(value) || value.length === 0) {
    fail(`${keyPath} must be a non-empty array`);
  }

  const seen = new Set();
  for (const item of value) {
    if (!item || typeof item !== 'object' || Array.isArray(item)) {
      fail(`${keyPath} must contain object entries`);
    }
    if (typeof item.name !== 'string' || item.name.trim().length === 0) {
      fail(`${keyPath} contains tool with invalid name`);
    }
    if (typeof item.description !== 'string' || item.description.trim().length === 0) {
      fail(`${keyPath} contains tool with invalid description`);
    }
    if (!item.inputSchema || typeof item.inputSchema !== 'object' || Array.isArray(item.inputSchema)) {
      fail(`${keyPath} contains tool with invalid inputSchema`);
    }
    if (seen.has(item.name)) {
      fail(`${keyPath} contains duplicate tool name: ${item.name}`);
    }
    seen.add(item.name);
  }
}

function rustArray(name, values) {
  const lines = values.map((value) => `    "${value}",`).join('\n');
  return `pub(crate) const ${name}: [&str; ${values.length}] = [\n${lines}\n];\n`;
}

function tsArray(name, values) {
  const lines = values.map((value) => `  "${value}",`).join('\n');
  return `export const ${name} = [\n${lines}\n] as const;\n`;
}

function uniqueStrings(values) {
  const seen = new Set();
  const out = [];
  for (const value of values) {
    if (!seen.has(value)) {
      seen.add(value);
      out.push(value);
    }
  }
  return out;
}

function listToolsPayloadRequiredToolNames(manifest) {
  return uniqueStrings([
    ...manifest.catalog.required_cognitive_core_tools,
    ...manifest.catalog.legacy_alias_tools,
  ]);
}

function rustRawJsonConst(name, value) {
  const json = JSON.stringify(value, null, 2);
  return `pub(crate) const ${name}: &str = r##"${json}"##;\n`;
}

function tsValue(name, value) {
  return `export const ${name} = ${JSON.stringify(value, null, 2)} as const;\n`;
}

function renderRust(manifest) {
  const header = `// AUTO-GENERATED by scripts/generate-mcp-contract-artifacts.mjs\n// Source: docs/runtime-migration/contracts/runtime-v1/mcp-tooling.manifest.json\n// DO NOT EDIT MANUALLY.\n\n`;
  return [
    header,
    `pub(crate) const MCP_TOOLING_CONTRACT_VERSION: &str = "${manifest.version}";\n\n`,
    rustArray('ACCEPTED_NAME_FIELDS', manifest.call_tool.accepted_name_fields),
    '\n',
    rustArray('ACCEPTED_ARGS_FIELDS', manifest.call_tool.accepted_args_fields),
    '\n',
    rustArray('DEFAULT_COGNITIVE_TOOL_CATALOG', manifest.catalog.default_cognitive_tools),
    '\n',
    rustArray('REQUIRED_COGNITIVE_CORE_TOOLS', manifest.catalog.required_cognitive_core_tools),
    '\n',
    rustArray('LEGACY_ALIAS_TOOL_CATALOG', manifest.catalog.legacy_alias_tools),
    '\n',
    rustArray('LEGACY_DEFI_COMPAT_TOOL_CATALOG', manifest.catalog.legacy_defi_compat_tools),
    '\n',
    rustArray(
      'LIST_TOOLS_PAYLOAD_REQUIRED_TOOL_NAMES',
      listToolsPayloadRequiredToolNames(manifest)
    ),
    '\n',
    rustRawJsonConst('LIST_TOOLS_STATIC_JSON', manifest.list_tools.static_tools),
    '\n',
    `pub(crate) fn list_tools_static_catalog() -> Vec<serde_json::Value> {\n    serde_json::from_str(LIST_TOOLS_STATIC_JSON).unwrap_or_else(|_| Vec::new())\n}\n`,
  ].join('');
}

function renderTs(manifest) {
  const header = `// AUTO-GENERATED by scripts/generate-mcp-contract-artifacts.mjs\n// Source: docs/runtime-migration/contracts/runtime-v1/mcp-tooling.manifest.json\n// DO NOT EDIT MANUALLY.\n\n`;
  return [
    header,
    `export const MCP_TOOLING_CONTRACT_VERSION = "${manifest.version}" as const;\n\n`,
    tsArray('ACCEPTED_NAME_FIELDS', manifest.call_tool.accepted_name_fields),
    '\n',
    tsArray('ACCEPTED_ARGS_FIELDS', manifest.call_tool.accepted_args_fields),
    '\n',
    tsArray('DEFAULT_COGNITIVE_TOOL_CATALOG', manifest.catalog.default_cognitive_tools),
    '\n',
    tsArray('REQUIRED_COGNITIVE_CORE_TOOLS', manifest.catalog.required_cognitive_core_tools),
    '\n',
    tsArray('LEGACY_ALIAS_TOOL_CATALOG', manifest.catalog.legacy_alias_tools),
    '\n',
    tsArray('LEGACY_DEFI_COMPAT_TOOL_CATALOG', manifest.catalog.legacy_defi_compat_tools),
    '\n',
    tsArray(
      'LIST_TOOLS_PAYLOAD_REQUIRED_TOOL_NAMES',
      listToolsPayloadRequiredToolNames(manifest)
    ),
    '\n',
    tsValue('LIST_TOOLS_STATIC', manifest.list_tools.static_tools),
  ].join('');
}

function syncFile(filePath, content, checkOnly) {
  const rel = path.relative(repoRoot, filePath);
  const exists = fs.existsSync(filePath);
  const current = exists ? fs.readFileSync(filePath, 'utf8') : '';

  if (current === content) {
    return { changed: false, file: rel };
  }

  if (checkOnly) {
    return { changed: true, file: rel };
  }

  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, 'utf8');
  return { changed: true, file: rel };
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const manifest = readJson(args.manifest);

  if (typeof manifest.version !== 'string' || manifest.version.trim().length === 0) {
    fail('version must be a non-empty string');
  }
  if (!manifest.catalog || typeof manifest.catalog !== 'object') {
    fail('catalog must be an object');
  }
  if (!manifest.call_tool || typeof manifest.call_tool !== 'object') {
    fail('call_tool must be an object');
  }
  if (!manifest.list_tools || typeof manifest.list_tools !== 'object') {
    fail('list_tools must be an object');
  }

  assertStringArray(manifest.catalog.default_cognitive_tools, 'catalog.default_cognitive_tools');
  assertStringArray(
    manifest.catalog.required_cognitive_core_tools,
    'catalog.required_cognitive_core_tools'
  );
  assertStringArray(manifest.catalog.legacy_alias_tools, 'catalog.legacy_alias_tools');
  assertStringArray(
    manifest.catalog.legacy_defi_compat_tools,
    'catalog.legacy_defi_compat_tools'
  );
  assertStringArray(manifest.call_tool.accepted_name_fields, 'call_tool.accepted_name_fields');
  assertStringArray(manifest.call_tool.accepted_args_fields, 'call_tool.accepted_args_fields');
  assertToolDefinitions(manifest.list_tools.static_tools, 'list_tools.static_tools');

  const knownToolNames = new Set(manifest.list_tools.static_tools.map((tool) => tool.name));
  for (const catalogName of [
    ...manifest.catalog.default_cognitive_tools,
    ...manifest.catalog.required_cognitive_core_tools,
    ...manifest.catalog.legacy_alias_tools,
    ...manifest.catalog.legacy_defi_compat_tools,
  ]) {
    if (!knownToolNames.has(catalogName)) {
      fail(`catalog references unknown tool in list_tools.static_tools: ${catalogName}`);
    }
  }

  const rustOutPath = path.resolve(repoRoot, 'crates/mcp-server/src/generated/mcp_contract.rs');
  const tsOutPath = path.resolve(repoRoot, 'scripts/generated/mcp_contract.generated.ts');

  const results = [
    syncFile(rustOutPath, renderRust(manifest), args.check),
    syncFile(tsOutPath, renderTs(manifest), args.check),
  ];

  const changed = results.filter((item) => item.changed);
  if (args.check) {
    if (changed.length === 0) {
      console.log('mcp-contract-codegen: up to date');
      return;
    }
    console.error('mcp-contract-codegen: out of date files detected:');
    for (const item of changed) {
      console.error(`- ${item.file}`);
    }
    process.exit(1);
  }

  if (changed.length === 0) {
    console.log('mcp-contract-codegen: no changes');
    return;
  }

  console.log('mcp-contract-codegen: updated files:');
  for (const item of changed) {
    console.log(`- ${item.file}`);
  }
}

main();
